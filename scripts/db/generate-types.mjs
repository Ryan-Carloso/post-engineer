#!/usr/bin/env node
//---------------
// generate-types — TypeScript row types for supabase-js, generated from
// supabase/schema.snapshot.json (never hand-written):
//
//   node scripts/db/generate-types.mjs --write   regenerate
//   node scripts/db/generate-types.mjs --check   fail when the file is stale
//
// Output: apps/web/lib/supabase/database.gen.ts. `createClient<Database>`
// then makes tsc reject a column that does not exist, a NOT NULL column
// missing from an insert, a wrong value type, and — because enum CHECK
// constraints become literal unions — a provider/mode value the database
// would refuse.
//---------------

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SNAPSHOT_PATH = join(ROOT, 'supabase', 'schema.snapshot.json');
const OUTPUT_PATH = join(ROOT, 'apps', 'web', 'lib', 'supabase', 'database.gen.ts');

const SCALAR_TYPES = new Map([
  ['text', 'string'],
  ['uuid', 'string'],
  ['timestamp with time zone', 'string'],
  ['date', 'string'],
  ['boolean', 'boolean'],
  ['integer', 'number'],
  ['bigint', 'number'],
  ['numeric', 'number'],
  ['double precision', 'number'],
  ['real', 'number'],
  ['jsonb', 'Json'],
  ['json', 'Json'],
]);

function scalarType(pgType, enums) {
  if (pgType.endsWith('[]')) return `${scalarType(pgType.slice(0, -2), enums)}[]`;
  const mapped = SCALAR_TYPES.get(pgType);
  if (mapped !== undefined) return mapped;
  const labels = enums[pgType];
  if (labels !== undefined) return labels.map((label) => `'${label}'`).join(' | ');
  throw new Error(`generate-types: unmapped Postgres type "${pgType}"; add it to SCALAR_TYPES`);
}

// `col = ANY (ARRAY['a'::text, 'b'::text])` inside a CHECK narrows the
// column to the literal union, including the `col IS NULL OR` form.
function enumChecks(constraints) {
  const narrowed = new Map();
  for (const definition of Object.values(constraints)) {
    if (!definition.startsWith('CHECK')) continue;
    const match = /(\w+) = ANY \(ARRAY\[([^\]]*)\]\)/.exec(definition);
    if (match === null) continue;
    const values = [...match[2].matchAll(/'([^']*)'::text/g)].map((value) => `'${value[1]}'`);
    narrowed.set(match[1], values.join(' | '));
  }
  return narrowed;
}

function renderTable(name, table, enums) {
  const narrowed = enumChecks(table.constraints);
  const row = [];
  const insert = [];
  const update = [];
  for (const column of table.columns) {
    const base = narrowed.get(column.name) ?? scalarType(column.type, enums);
    const type = column.notNull ? base : `${base} | null`;
    const optionalOnInsert = !column.notNull || column.default !== null;
    row.push(`        ${column.name}: ${type};`);
    insert.push(`        ${column.name}${optionalOnInsert ? '?' : ''}: ${type};`);
    update.push(`        ${column.name}?: ${type};`);
  }
  return [
    `      ${name}: {`,
    `        Row: {\n${row.join('\n')}\n        };`,
    `        Insert: {\n${insert.join('\n')}\n        };`,
    `        Update: {\n${update.join('\n')}\n        };`,
    '        Relationships: [];',
    '      };',
  ].join('\n');
}

function render(snapshot) {
  const names = Object.keys(snapshot.tables).sort();
  const tables = names.map((name) => renderTable(name, snapshot.tables[name], snapshot.enums)).join('\n');
  return `// GENERATED by scripts/db/generate-types.mjs from supabase/schema.snapshot.json.
// Do not edit by hand: regenerate with \`node scripts/db/generate-types.mjs --write\`.

// jsonb columns are \`unknown\`: the database does not constrain their shape and
// callers pass plain Record<string, unknown> metadata blobs. Shape checks for
// those belong to runtime guards, not to this type.
export type Json = unknown;

export interface Database {
  public: {
    Tables: {
${tables}
    };
    Views: Record<string, never>;
    // RPC signatures are not in the snapshot yet: any RPC name with named args.
    Functions: Record<string, { Args: Record<string, unknown>; Returns: unknown }>;
    Enums: Record<string, never>;
    CompositeTypes: Record<string, never>;
  };
}
`;
}

function main() {
  const write = process.argv.includes('--write');
  const check = process.argv.includes('--check');
  if (write === check) {
    console.error('usage: generate-types.mjs (--write | --check)');
    process.exit(2);
  }
  const fresh = render(JSON.parse(readFileSync(SNAPSHOT_PATH, 'utf8')));
  if (write) {
    writeFileSync(OUTPUT_PATH, fresh);
    console.log(`wrote ${OUTPUT_PATH}`);
    return;
  }
  if (readFileSync(OUTPUT_PATH, 'utf8') !== fresh) {
    console.error('apps/web/lib/supabase/database.gen.ts is stale: run node scripts/db/generate-types.mjs --write');
    process.exit(1);
  }
  console.log('database.gen.ts is up to date');
}

main();
