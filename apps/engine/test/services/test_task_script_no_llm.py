"""Task script generation without the LLM script branch (Phase 5, PR 1).

The script now arrives with the job (segments joined by the caller) and is
never generated, angled, or repaired by the LLM inside the task pipeline:

- An empty script fails the task loudly, with no web search and no LLM call.
- A supplied script passes through unchanged, with no LLM call.
- A supplied script with no valid hook under an active lip-sync intro
  raises instead of being regenerated by the LLM (the outer task runner
  turns the raise into a loud task failure).

The POST /videos endpoint itself stays: the web generate-and-schedule
route dispatches every segments job through it (startEngineVideoTask),
so removing the route would break the live segments pipeline. Only the
dead _persona_video_params builder (zero callers) is removed.
"""

from unittest.mock import patch

import pytest

from app.controllers.v1 import video as video_controller
from app.models.schema import PersonaParams, VideoParams
from app.services import task as tm


def _persona_params(**overrides) -> VideoParams:
    return VideoParams(
        video_subject="coffee",
        video_language="en-US",
        persona=PersonaParams(
            name="Ana",
            photo_url="https://supabase.test/signed/foto.png",
            voice_id="calm",
            niche="home barista",
        ),
        **overrides,
    )


def test_empty_script_fails_without_search_or_llm():
    params = VideoParams(video_subject="coffee", video_script="")
    with (
        patch.object(tm, "_fail_task") as fail_task,
        patch.object(tm.llm, "generate_script") as generate,
    ):
        result = tm.generate_script("empty-task", params)

    assert result is None
    fail_task.assert_called_once_with(
        "empty-task", "failed to generate video script", params, stage="script"
    )
    generate.assert_not_called()


def test_supplied_script_passes_without_llm():
    script = "Hook sentence here.\n\nBody sentence here."
    params = VideoParams(video_subject="coffee", video_script=script)
    with (
        patch.object(tm.llm, "generate_script") as generate,
    ):
        assert tm.generate_script("supplied-task", params) == script

    generate.assert_not_called()


def test_supplied_script_with_valid_lipsync_hook_passes_without_llm():
    script = "Hook sentence here.\n\nBody sentence here."
    params = _persona_params(video_script=script)
    with patch.object(tm.llm, "generate_script") as generate:
        assert tm.generate_script("hook-ok-task", params) == script

    generate.assert_not_called()


def test_single_paragraph_lipsync_script_raises_instead_of_regenerating():
    params = _persona_params(video_script="Only one paragraph here.")
    with patch.object(tm.llm, "generate_script") as generate:
        with pytest.raises(ValueError, match="no valid hook"):
            tm.generate_script("hook-single-task", params)

    generate.assert_not_called()


def test_lipsync_script_without_terminal_hook_punctuation_raises():
    params = _persona_params(video_script="Hook without terminal punctuation\n\nBody sentence here.")
    with patch.object(tm.llm, "generate_script") as generate:
        with pytest.raises(ValueError, match="no valid hook"):
            tm.generate_script("hook-punct-task", params)

    generate.assert_not_called()


def test_videos_endpoint_still_serves_segment_jobs():
    # The web generate-and-schedule route dispatches segments jobs via
    # POST /api/v1/videos (startEngineVideoTask); the route must stay.
    paths = {
        (getattr(route, "path", None), method)
        for route in video_controller.router.routes
        for method in (getattr(route, "methods", None) or set())
    }
    assert ("/api/v1/videos", "POST") in paths
    assert ("/api/v1/subtitle", "POST") in paths
    assert ("/api/v1/audio", "POST") in paths


def test_persona_video_params_builder_is_removed():
    # The builder constructed script-less, prompt-only requests that only
    # ever worked via LLM script generation, and nothing called it.
    assert not hasattr(video_controller, "_persona_video_params")
