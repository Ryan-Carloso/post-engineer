-- 073: schedules.post_cta_type is nullable (issue #639).
--
-- Migration 072 made post_cta_type NOT NULL DEFAULT 'follow', but a
-- schedule legitimately has no CTA: every faceless post, and every video
-- with a per-video `cta: null` override. The snapshot writer
-- (buildIdentitySnapshot) stores NULL for those, so the NOT NULL check
-- rejected the row and the route took the generic 500-after-spend branch.
-- NULL means "no CTA on this post"; it must NOT fall back to 'follow',
-- which would read back as a follow CTA and mismatch a no-CTA pair
-- partner in experiment-link.ts. The CHECK still admits only the seven
-- intent values for non-NULL rows (NULL passes a CHECK in Postgres).
alter table public.schedules alter column post_cta_type drop not null;
